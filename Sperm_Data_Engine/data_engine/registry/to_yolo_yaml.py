"""
to_yolo_yaml.py -- generate a sperm_dataset.yaml-shaped file from the registry.

Run as a module from the repo root, e.g.:

    python -m data_engine.registry.to_yolo_yaml --out data_engine/generated_dataset.yaml
    python -m data_engine.registry.to_yolo_yaml --tier 40 --tier 160 --out data_engine/dense_only.yaml

With no filters, every registered clip is included.

DATA-ENGINE FIX: train/val entries used to be a bare f"{clip_id}/images",
resolved against one shared "path:" root (the legacy data/ folder) --
correct only as long as every clip actually lived under data/<clip_id>/.
Confirmed by an actual training run to silently break the moment any clip
lives elsewhere (e.g. real_40_20260902-100300, registered under
data_engine/data/ -- which is ingest.py's own default output root, so this
was a live bug for every synthetic/augmented/pipeline-ingested clip this
whole session, just never exercised by an actual multi-clip training run
until now): Ultralytics resolved its relative path against the wrong root
and raised FileNotFoundError. Fixed by emitting each entry as clip.path's
own absolute images/ directory instead of a clip_id-relative guess --
correct regardless of where a clip actually lives, and "path:" no longer
needs to be a single shared root at all (an absolute train/val entry is
used as-is by Ultralytics/pathlib's own path-joining regardless of what
"path:" says).
"""
import argparse
from pathlib import Path

import yaml

from data_engine.registry.registry import REPO_ROOT, Registry


def _images_dir(clip) -> str:
    return str((REPO_ROOT / clip.path / "images").resolve()).replace("\\", "/")


def build_yaml(registry: Registry, tiers=None, source_types=None, data_root=None) -> dict:
    clips = registry.clips
    if tiers:
        clips = [c for c in clips if c.density_tier in tiers]
    if source_types:
        clips = [c for c in clips if c.source_type in source_types]

    train = sorted(_images_dir(c) for c in clips if c.split == "train")
    val = sorted(_images_dir(c) for c in clips if c.split == "val")

    return {
        "path": str(data_root or REPO_ROOT).replace("\\", "/"),
        "train": train,
        "val": val,
        "nc": 1,
        "names": {0: "sperm"},
    }


def _cli():
    parser = argparse.ArgumentParser(description="Generate a YOLO dataset yaml from the registry")
    parser.add_argument("--tier", action="append", default=None, help="Filter to this density tier (repeatable)")
    parser.add_argument("--source", action="append", default=None, help="Filter to this source_type (repeatable)")
    parser.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parents[1] / "generated_dataset.yaml"),
    )
    args = parser.parse_args()

    registry = Registry.load()
    doc = build_yaml(registry, tiers=args.tier, source_types=args.source)

    with open(args.out, "w") as f:
        f.write("# Auto-generated by data_engine/registry/to_yolo_yaml.py -- do not hand-edit.\n")
        f.write("# Edit data_engine/registry/manifest.yaml (or use Registry.add_clip) instead.\n\n")
        yaml.safe_dump(doc, f, sort_keys=False)

    print(f"Wrote {args.out} ({len(doc['train'])} train, {len(doc['val'])} val clips)")


if __name__ == "__main__":
    _cli()
